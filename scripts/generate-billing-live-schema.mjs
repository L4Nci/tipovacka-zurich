import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = fileURLToPath(new URL('../supabase/migrations/20261110195526_billing_test_sandbox.sql', import.meta.url));
const target = fileURLToPath(new URL('../supabase/migrations/20261112101432_billing_live_preparation.sql', import.meta.url));
const delta = fileURLToPath(new URL('../supabase/templates/billing_live_projection.sql', import.meta.url));
const original = readFileSync(source, 'utf8').trimEnd();
let shared = original.replaceAll('billing_test_', 'billing_live_').replaceAll('cs_test_', 'cs_live_')
  .replace('livemode boolean NOT NULL DEFAULT false CHECK (livemode=false)', 'livemode boolean NOT NULL DEFAULT true CHECK (livemode=true)')
  .replaceAll("'test'", "'live'").replaceAll("'false'::jsonb", "'true'::jsonb")
  .replace("'type',event_type,'livemode',false", "'type',event_type,'livemode',true");
const hook = "  UPDATE billing_live_private.events SET state='completed',completed_at=clock_timestamp()";
if (shared.split(hook).length !== 2 || !shared.includes("p_event->'livemode' IS DISTINCT FROM 'true'::jsonb")
  || !shared.includes("'type',event_type,'livemode',true")
  || !shared.includes('livemode boolean NOT NULL DEFAULT true CHECK (livemode=true)')
  || shared.includes('cs_test_')) throw Error('Shared ledger generator invariant failed');
shared = shared.replace(hook, `  PERFORM public.billing_live_project_entitlements(p_account_id,p_player_id,p_intent_id);\n${hook}`);
const generated = `-- GENERATED by scripts/generate-billing-live-schema.mjs. Do not hand-edit.\n-- Shared ledger source is the TEST candidate; LIVE projection delta is separate.\n-- No account, policy, price, plan, entitlement, grant or enabled state is seeded.\n${shared}\n\n${readFileSync(delta, 'utf8').trimEnd()}\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) { console.error('Generated Live migration is stale.'); process.exitCode = 1; }
} else writeFileSync(target, generated);
